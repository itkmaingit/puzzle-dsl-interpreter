median_val = statistics.median(diffs)
var_val = statistics.pstdev(diffs)  # サンプル分散

print("平均(生成時間) =", mean_val)
print("中央値(生成時間) =", median_val)
print("標準偏差(生成時間) =", var_val)

# ---- 4) 生成間隔のヒストグラムを描画・保存 ----
plt.figure(figsize=(8, 4))
